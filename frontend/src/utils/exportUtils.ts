/**
 * Utilities for copying, sharing, and exporting chat messages and conversations.
 */

import { jsPDF } from "jspdf";
import type { ChatMessage } from "../types/chat";
import { formatTimestamp } from "./formatters";

/**
 * Fallback clipboard write using a temporary hidden textarea.
 */
function fallbackCopyToClipboard(text: string): boolean {
  try {
    const textArea = document.createElement("textarea");
    textArea.value = text;
    textArea.style.top = "0";
    textArea.style.left = "0";
    textArea.style.position = "fixed";
    textArea.style.opacity = "0";
    document.body.appendChild(textArea);
    textArea.focus();
    textArea.select();
    const successful = document.execCommand("copy");
    document.body.removeChild(textArea);
    return successful;
  } catch {
    return false;
  }
}

/**
 * Safe clipboard write supporting both modern navigator.clipboard and legacy fallback.
 */
export async function writeToClipboard(text: string): Promise<boolean> {
  if (navigator?.clipboard?.writeText) {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch {
      return fallbackCopyToClipboard(text);
    }
  }
  return fallbackCopyToClipboard(text);
}

/**
 * Format a single message into human-readable text including citations.
 */
export function formatSingleMessage(message: ChatMessage): string {
  const isStudent = message.role === "student";
  const author = isStudent ? "Student" : `SmartCollege AI${message.collegeName ? ` (${message.collegeName})` : ""}`;
  const time = formatTimestamp(message.timestamp);

  let output = `[${author} - ${time}]\n${message.content}`;

  if (!isStudent && message.meta) {
    if (message.meta.source) {
      output += `\n\nOfficial Source: ${message.meta.source}`;
    }
    if (message.meta.lastVerified) {
      output += `\nVerified Date: ${message.meta.lastVerified}`;
    }
    if (message.meta.verificationStatus) {
      output += `\nVerification Status: ${message.meta.verificationStatus}`;
    }
  }

  return output;
}

/**
 * Format a complete conversation into human-readable structured text.
 */
export function formatFullConversation(
  messages: ChatMessage[],
  collegeName?: string | null
): string {
  const header = [
    "==================================================================",
    "SmartCollege AI — Student Conversation Record",
    `Institution: ${collegeName || "General Student Support"}`,
    `Export Date: ${new Date().toLocaleString()}`,
    `Total Messages: ${messages.length}`,
    "==================================================================\n",
  ].join("\n");

  const messageBlocks = messages.map((msg, index) => {
    const divider = index > 0 ? "------------------------------------------------------------------\n" : "";
    return `${divider}${formatSingleMessage(msg)}`;
  });

  const footer = [
    "\n==================================================================",
    "Generated by SmartCollege AI Assistant",
    "Strict College Isolation • Official Sources Cited",
    "==================================================================",
  ].join("\n");

  return `${header}\n${messageBlocks.join("\n\n")}\n${footer}`;
}

/**
 * Copy an individual message to clipboard.
 */
export async function copyMessageText(message: ChatMessage): Promise<boolean> {
  const text = formatSingleMessage(message);
  return writeToClipboard(text);
}

/**
 * Copy complete conversation to clipboard.
 */
export async function copyConversationText(
  messages: ChatMessage[],
  collegeName?: string | null
): Promise<boolean> {
  if (messages.length === 0) return false;
  const text = formatFullConversation(messages, collegeName);
  return writeToClipboard(text);
}

/**
 * Share an individual message using Web Share API with clipboard fallback.
 */
export async function shareMessage(
  message: ChatMessage
): Promise<{ shared: boolean; copied: boolean }> {
  const text = formatSingleMessage(message);
  const title = `SmartCollege AI Response`;

  if (navigator?.share) {
    try {
      await navigator.share({
        title,
        text,
      });
      return { shared: true, copied: false };
    } catch (err: unknown) {
      // If user aborted/cancelled the share dialog, return cleanly without error
      if (err instanceof Error && err.name === "AbortError") {
        return { shared: false, copied: false };
      }
      // Otherwise fall back to clipboard
    }
  }

  const copied = await writeToClipboard(text);
  return { shared: false, copied };
}

/**
 * Share complete conversation using Web Share API with clipboard fallback.
 */
export async function shareConversation(
  messages: ChatMessage[],
  collegeName?: string | null
): Promise<{ shared: boolean; copied: boolean }> {
  if (messages.length === 0) return { shared: false, copied: false };

  const text = formatFullConversation(messages, collegeName);
  const title = `SmartCollege AI Conversation (${collegeName || "General"})`;

  if (navigator?.share) {
    try {
      await navigator.share({
        title,
        text,
      });
      return { shared: true, copied: false };
    } catch (err: unknown) {
      if (err instanceof Error && err.name === "AbortError") {
        return { shared: false, copied: false };
      }
    }
  }

  const copied = await writeToClipboard(text);
  return { shared: false, copied };
}

/**
 * Download complete conversation as a formatted .txt document.
 */
export function exportConversationAsTxt(
  messages: ChatMessage[],
  collegeName?: string | null
): void {
  if (messages.length === 0) return;

  const content = formatFullConversation(messages, collegeName);
  const blob = new Blob([content], { type: "text/plain;charset=utf-8" });
  const url = URL.createObjectURL(blob);

  const safeCollege = (collegeName || "General")
    .replace(/[^a-zA-Z0-9_-]/g, "_")
    .slice(0, 30);
  const dateStr = new Date().toISOString().slice(0, 10);
  const fileName = `SmartCollege_${safeCollege}_${dateStr}.txt`;

  const link = document.createElement("a");
  link.href = url;
  link.download = fileName;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Export complete conversation as a structured multi-page PDF document.
 */
export function exportConversationAsPdf(
  messages: ChatMessage[],
  collegeName?: string | null
): void {
  if (messages.length === 0) return;

  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 16;
  const contentWidth = pageWidth - margin * 2;
  let yPos = margin;

  // Colors
  const primaryColor = [37, 99, 235]; // #2563EB
  const textDark = [15, 23, 42]; // #0F172A
  const textGray = [100, 116, 139]; // #64748B
  const bgLight = [248, 250, 252]; // #F8FAFC
  const borderLight = [226, 232, 240]; // #E2E8F0

  const checkPageBreak = (neededHeight: number) => {
    if (yPos + neededHeight > pageHeight - margin - 10) {
      doc.addPage();
      yPos = margin + 5;
    }
  };

  // Initial Cover / Header Block (yPos initialized to margin + 5)
  yPos = margin + 5;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.setTextColor(primaryColor[0], primaryColor[1], primaryColor[2]);
  doc.text("SmartCollege AI", margin, yPos);
  yPos += 6;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(textGray[0], textGray[1], textGray[2]);
  doc.text("Student Conversation Record & Verification Log", margin, yPos);
  yPos += 5;

  doc.setDrawColor(borderLight[0], borderLight[1], borderLight[2]);
  doc.setLineWidth(0.3);
  doc.line(margin, yPos, margin + contentWidth, yPos);
  yPos += 5;

  // Metadata Card
  doc.setFillColor(bgLight[0], bgLight[1], bgLight[2]);
  doc.roundedRect(margin, yPos, contentWidth, 18, 2, 2, "F");
  doc.setDrawColor(borderLight[0], borderLight[1], borderLight[2]);
  doc.roundedRect(margin, yPos, contentWidth, 18, 2, 2, "S");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.setTextColor(textDark[0], textDark[1], textDark[2]);
  doc.text(`Active Institution:`, margin + 4, yPos + 6);
  doc.setFont("helvetica", "normal");
  doc.text(`${collegeName || "General Student Support"}`, margin + 35, yPos + 6);

  doc.setFont("helvetica", "bold");
  doc.text(`Generated On:`, margin + 4, yPos + 12);
  doc.setFont("helvetica", "normal");
  doc.text(`${new Date().toLocaleString()}`, margin + 35, yPos + 12);

  doc.text(`Total Messages: ${messages.length}`, margin + contentWidth - 40, yPos + 6);

  yPos += 24;

  // Render Messages
  messages.forEach((msg, idx) => {
    const isStudent = msg.role === "student";
    const author = isStudent ? "Student Question" : `SmartCollege AI Answer`;
    const timeStr = formatTimestamp(msg.timestamp);

    // Calculate height needed for content
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9.5);
    const splitContent = doc.splitTextToSize(msg.content, contentWidth - 8);
    const contentLines = splitContent.length;
    let blockHeight = 12 + contentLines * 4.5;

    let sourceLines: string[] = [];
    if (!isStudent && msg.meta?.source) {
      sourceLines = doc.splitTextToSize(`Source: ${msg.meta.source}`, contentWidth - 8);
      blockHeight += sourceLines.length * 4 + 4;
    }

    checkPageBreak(blockHeight + 6);

    // Message Card Background
    if (isStudent) {
      doc.setFillColor(239, 246, 255); // #EFF6FF (Light Blue)
      doc.setDrawColor(191, 219, 254);
    } else {
      doc.setFillColor(255, 255, 255); // White
      doc.setDrawColor(226, 232, 240);
    }

    doc.roundedRect(margin, yPos, contentWidth, blockHeight, 2, 2, "FD");

    // Header inside card
    doc.setFont("helvetica", "bold");
    doc.setFontSize(8.5);
    if (isStudent) {
      doc.setTextColor(29, 78, 216); // Blue-700
    } else {
      doc.setTextColor(109, 40, 217); // Purple-700
    }
    doc.text(`#${idx + 1}  ${author}`, margin + 4, yPos + 6);

    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(textGray[0], textGray[1], textGray[2]);
    doc.text(timeStr, margin + contentWidth - 30, yPos + 6);

    // Message Content
    let textY = yPos + 11;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9.5);
    doc.setTextColor(textDark[0], textDark[1], textDark[2]);
    doc.text(splitContent, margin + 4, textY);
    textY += contentLines * 4.5;

    // Source Citation
    if (sourceLines.length > 0) {
      doc.setFont("helvetica", "italic");
      doc.setFontSize(8);
      doc.setTextColor(37, 99, 235);
      doc.text(sourceLines, margin + 4, textY + 2);
    }

    yPos += blockHeight + 4;
  });

  // Footer on each page
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(textGray[0], textGray[1], textGray[2]);
    doc.text(
      "SmartCollege AI — Multi-College Support Portal | Official Source Citations",
      margin,
      pageHeight - 6
    );
    doc.text(`Page ${i} of ${totalPages}`, margin + contentWidth - 20, pageHeight - 6);
  }

  // Trigger browser download
  const safeCollege = (collegeName || "General")
    .replace(/[^a-zA-Z0-9_-]/g, "_")
    .slice(0, 30);
  const dateStr = new Date().toISOString().slice(0, 10);
  const fileName = `SmartCollege_${safeCollege}_${dateStr}.pdf`;

  doc.save(fileName);
}

